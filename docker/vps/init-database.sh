#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<'SQL'
\getenv app_password POSTGRES_APP_PASSWORD
CREATE ROLE swi_app LOGIN PASSWORD :'app_password';
GRANT CONNECT ON DATABASE swi TO swi_app;
GRANT USAGE ON SCHEMA public TO swi_app;
ALTER DEFAULT PRIVILEGES FOR ROLE swi IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO swi_app;
ALTER DEFAULT PRIVILEGES FOR ROLE swi IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO swi_app;
SQL
